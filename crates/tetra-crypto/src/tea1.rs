/// Generate TEA1 keystream bytes for an air-interface IV and 80-bit key.
pub fn tea1(iv: u32, key: &[u8; 10], output: &mut [u8]) {
    let mut state = expand_iv(iv);
    let mut key_register = init_key_register(key);
    let mut skip_rounds = 54;

    for byte in output {
        for _ in 0..skip_rounds {
            let sbox_output = SBOX[((key_register >> 24 ^ key_register) & 0xff) as usize];
            key_register = (key_register << 8) | u32::from(sbox_output);
            let derived_12 = state_word_to_new_byte(((state >> 8) & 0xffff) as u16, &LUT_A);
            let derived_56 = state_word_to_new_byte(((state >> 40) & 0xffff) as u16, &LUT_B);
            let reordered_4 = reorder_state_byte((state >> 32) as u8);
            let new_byte = derived_56 ^ (state >> 56) as u8 ^ reordered_4 ^ sbox_output;
            state = ((state << 8) ^ (u64::from(derived_12) << 32)) | u64::from(new_byte);
        }
        *byte = (state >> 56) as u8;
        skip_rounds = 19;
    }
}

fn expand_iv(short_iv: u32) -> u64 {
    let xorred = (short_iv ^ 0x9672_4fa1).rotate_left(8);
    ((u64::from(short_iv) << 32) | u64::from(xorred)).rotate_right(8)
}

fn init_key_register(key: &[u8; 10]) -> u32 {
    key.iter().fold(0_u32, |state, key_byte| {
        (state << 8) | u32::from(SBOX[((state >> 24 ^ state ^ u32::from(*key_byte)) & 0xff) as usize])
    })
}

fn state_word_to_new_byte(state: u16, lut: &[u16; 8]) -> u8 {
    let (mut low, mut high) = (state as u8, (state >> 8) as u8);
    let mut output = 0;
    for (i, value) in lut.iter().enumerate() {
        let distance = ((low >> 7) & 1) | ((low << 1) & 2) | ((high << 1) & 12);
        if value & (1 << distance) != 0 {
            output |= 1 << i;
        }
        low = low.rotate_right(1);
        high = high.rotate_right(1);
    }
    output
}

fn reorder_state_byte(state: u8) -> u8 {
    ((state << 6) & 0x40)
        | ((state << 1) & 0x20)
        | ((state << 2) & 0x08)
        | ((state >> 3) & 0x14)
        | ((state >> 2) & 0x01)
        | ((state >> 5) & 0x02)
        | ((state << 4) & 0x80)
}

#[cfg(test)]
mod tests {
    use super::tea1;
    #[test]
    fn reference_vectors() {
        let mut output = [0; 10];
        tea1(0x1111_1111, &[0; 10], &mut output);
        assert_eq!(output, [0xd3, 0x3f, 0xd8, 0xa6, 0x05, 0xa0, 0xa1, 0xbb, 0x90, 0x23]);
        tea1(
            0x0123_4567,
            &[0xa7, 0x98, 0x39, 0xe4, 0xba, 0x88, 0xee, 0x54, 0xa0, 0x29],
            &mut output,
        );
        assert_eq!(output, [0x1d, 0xec, 0x9c, 0x7e, 0xc6, 0x22, 0x3d, 0x87, 0xc2, 0xcc]);
    }
}
