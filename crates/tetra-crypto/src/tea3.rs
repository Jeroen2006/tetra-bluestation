/// Generate TEA3 keystream bytes for an air-interface IV and 80-bit key.
pub fn tea3(iv: u32, key: &[u8; 10], output: &mut [u8]) {
    let mut state = expand_iv(iv);
    let mut key_register = *key;
    let mut skip_rounds = 51;

    for byte in output {
        for _ in 0..skip_rounds {
            let sbox_output = SBOX[(key_register[7] ^ key_register[2]) as usize] ^ key_register[0];
            key_register.copy_within(1.., 0);
            key_register[9] = sbox_output;
            let derived_12 = state_word_to_new_byte(((state >> 8) & 0xffff) as u16, &LUT_A);
            let derived_56 = state_word_to_new_byte(((state >> 40) & 0xffff) as u16, &LUT_B);
            let reordered_4 = reorder_state_byte((state >> 32) as u8);
            let new_byte = (state >> 56) as u8 ^ reordered_4 ^ derived_12 ^ sbox_output;
            state = ((state << 8) ^ (u64::from(derived_56) << 40)) | u64::from(new_byte);
        }
        *byte = (state >> 56) as u8;
        skip_rounds = 19;
    }
}

fn expand_iv(frame_numbers: u32) -> u64 {
    let xorred = (frame_numbers ^ 0xc43a_7d51).rotate_left(8);
    ((u64::from(frame_numbers) << 32) | u64::from(xorred)).rotate_right(8)
}

fn state_word_to_new_byte(state: u16, lut: &[u16; 8]) -> u8 {
    let (mut low, mut high) = (state as u8, (state >> 8) as u8);
    let mut output = 0;
    for (i, value) in lut.iter().enumerate() {
        let distance = ((low >> 5) & 3) | ((high >> 3) & 12);
        if value & (1 << distance) != 0 {
            output |= 1 << i;
        }
        low = low.rotate_right(1);
        high = high.rotate_right(1);
    }
    output
}

fn reorder_state_byte(state: u8) -> u8 {
    ((state << 6) & 0x40)
        | ((state << 1) & 0x20)
        | ((state << 2) & 0x98)
        | ((state >> 4) & 0x04)
        | ((state >> 3) & 0x01)
        | ((state >> 6) & 0x02)
}

#[cfg(test)]
mod tests {
    use super::tea3;
    #[test]
    fn reference_vectors() {
        let mut output = [0; 10];
        tea3(0x1111_1111, &[0; 10], &mut output);
        assert_eq!(output, [0x06, 0xa6, 0x58, 0x8c, 0x5d, 0x9a, 0x99, 0x6d, 0xd2, 0x5e]);
        tea3(
            0x0123_4567,
            &[0xa7, 0x98, 0x39, 0xe4, 0xba, 0x88, 0xee, 0x54, 0xa0, 0x29],
            &mut output,
        );
        assert_eq!(output, [0x02, 0x49, 0x1e, 0xf5, 0x57, 0xc5, 0x1c, 0x17, 0x73, 0x0c]);
    }
}
