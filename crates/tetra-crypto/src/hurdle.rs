pub(crate) struct Hurdle {
    round_keys: [[u8; 16]; 16],
}

impl Hurdle {
    pub(crate) fn new(key: &[u8; 16]) -> Self {
        let mut round_keys = [[0; 16]; 16];
        round_keys[0] = *key;
        for round in 1..16 {
            for index in 0..16 {
                round_keys[round][index] = round_keys[round - 1][(index + ROTATIONS[round]) & 15] ^ ROUND_CONSTANT[index];
            }
        }
        Self { round_keys }
    }

    pub(crate) fn encrypt(&self, input: &[u8; 8]) -> [u8; 8] {
        self.crypt(input, false)
    }
    pub(crate) fn decrypt(&self, input: &[u8; 8]) -> [u8; 8] {
        self.crypt(input, true)
    }

    fn crypt(&self, input: &[u8; 8], decrypt: bool) -> [u8; 8] {
        let mut lhs = u32::from_le_bytes(input[0..4].try_into().unwrap());
        let mut rhs = u32::from_le_bytes(input[4..8].try_into().unwrap());
        for index in 0..16 {
            let key_index = if decrypt { 15 - index } else { index };
            let feedback = u32::from_le_bytes(f(rhs.to_le_bytes(), &self.round_keys[key_index]));
            let next = lhs ^ feedback;
            lhs = rhs;
            rhs = next;
        }
        let mut output = [0; 8];
        output[0..4].copy_from_slice(&rhs.to_le_bytes());
        output[4..8].copy_from_slice(&lhs.to_le_bytes());
        output
    }
}

fn f(rhs: [u8; 4], key: &[u8; 16]) -> [u8; 4] {
    let mut s = SBOX[rhs[3].wrapping_add(key[15]) as usize];
    for (rhs_index, key_index) in [(2, 14), (1, 13), (0, 12)] {
        s = SBOX[(rhs[rhs_index].wrapping_add(key[key_index]) ^ s) as usize];
    }
    let mut output = 0_u32;
    for (rhs_index, key_index) in [(3, 11), (1, 10), (2, 9), (0, 8), (1, 7), (3, 6), (0, 5), (2, 4)] {
        s = SBOX[(rhs[rhs_index].wrapping_add(key[key_index]) ^ s) as usize];
        output = (output >> 1) | REORDER[(s & 0x0f) as usize];
    }
    output.to_le_bytes()
}

pub(crate) fn enc_cbc(plaintext: &[u8; 16], key: &[u8; 16]) -> [u8; 16] {
    let cipher = Hurdle::new(key);
    let first = cipher.encrypt(&plaintext[0..8].try_into().unwrap());
    let mut intermediate = [0; 8];
    for index in 0..8 {
        intermediate[index] = first[index] ^ plaintext[8 + index];
    }
    let second = cipher.encrypt(&intermediate);
    let mut output = [0; 16];
    output[0..8].copy_from_slice(&first);
    output[8..16].copy_from_slice(&second);
    output
}

pub(crate) fn dec_cts(ciphertext: &[u8; 15], key: &[u8; 16]) -> [u8; 15] {
    let cipher = Hurdle::new(key);
    let second: [u8; 8] = ciphertext[7..15].try_into().unwrap();
    let tail = cipher.decrypt(&second);
    let mut first_block = [0; 8];
    first_block[0..7].copy_from_slice(&ciphertext[0..7]);
    first_block[7] = tail[7];
    let first = cipher.decrypt(&first_block);
    let mut output = [0; 15];
    output[0..8].copy_from_slice(&first);
    for index in 0..7 {
        output[8 + index] = tail[index] ^ ciphertext[index];
    }
    output
}

pub(crate) fn sbox(value: u8) -> u8 {
    SBOX[value as usize]
}
pub(crate) fn inverse_sbox(value: u8) -> u8 {
    INV_SBOX[value as usize]
}

